/** Пустой адрес не стирает плейсхолдер. Заполненный подставляется тем же токеном, что и fillPlaceholders. */
export function cookieContactsText(label: string | null): string {
  if (!label) return COOKIE_CONTACTS_SENTENCE;
  return COOKIE_CONTACTS_SENTENCE.replaceAll("{{privacy_contact_email}}", label);
}
